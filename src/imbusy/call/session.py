"""CallSession: the five-turn state machine that drives the caller persona.

    RINGING -> OPENING -> HOOK -> ESCALATE -> ASK -> CLOSING -> ENDED

OPENING is the pre-written `opening_line`, played by ConversationRelay as `welcomeGreeting` (no
model latency on pickup). Each later state is one caller turn generated by the fast model, with the
system prompt recomposed from the script, the state and a one-line directive for that turn.
CLOSING says goodbye; the session then ends the call.

The session is transport-agnostic: it consumes user text and yields text deltas. The phone path
and the browser demo share it unchanged.
"""

from __future__ import annotations

import asyncio
import logging
from collections.abc import AsyncGenerator, Awaitable, Callable
from dataclasses import dataclass, field
from enum import StrEnum
from typing import Any

from imbusy.excuse.schema import BASE_FORBIDDEN, CallScript
from imbusy.llm import (
    ChatMessage,
    Effort,
    LLMClient,
    LLMError,
    ModelRole,
    StopReason,
    StreamEnd,
    TextDelta,
)
from imbusy.prompts import Prompt, load_prompt, load_yaml_prompt
from imbusy.safety.safeword import SafeWordMatcher

SafeWordCallback = Callable[[], Awaitable[None]]

logger = logging.getLogger(__name__)


class CallState(StrEnum):
    RINGING = "ringing"
    OPENING = "opening"
    HOOK = "hook"
    ESCALATE = "escalate"
    ASK = "ask"
    CLOSING = "closing"
    ENDED = "ended"


# The arc of a standard five-turn call. Shorter `max_turns` drop ESCALATE first, then HOOK.
ARC: tuple[CallState, ...] = (
    CallState.OPENING,
    CallState.HOOK,
    CallState.ESCALATE,
    CallState.ASK,
    CallState.CLOSING,
)

TRANSITIONS: dict[CallState, frozenset[CallState]] = {
    CallState.RINGING: frozenset({CallState.OPENING, CallState.ENDED}),
    CallState.OPENING: frozenset({CallState.HOOK, CallState.ESCALATE, CallState.ASK, CallState.CLOSING, CallState.ENDED}),
    CallState.HOOK: frozenset({CallState.ESCALATE, CallState.ASK, CallState.CLOSING, CallState.ENDED}),
    CallState.ESCALATE: frozenset({CallState.ASK, CallState.CLOSING, CallState.ENDED}),
    CallState.ASK: frozenset({CallState.ASK, CallState.CLOSING, CallState.ENDED}),
    CallState.CLOSING: frozenset({CallState.ENDED}),
    CallState.ENDED: frozenset(),
}  # fmt: skip

# Stage direction that opens the transcript: the Messages API needs a user turn first, and the
# caller's greeting is the first thing actually said.
CALL_CONNECTED = "[The call connects. They pick up.]"
REPLY_MAX_TOKENS = 300


class InvalidTransition(Exception):
    pass


def arc_for(max_turns: int) -> tuple[CallState, ...]:
    """States the call visits for a given turn budget (3..8).

    3 -> OPENING, ASK, CLOSING; 4 adds HOOK; 5 is the full arc; above 5, ASK repeats so the caller
    can insist once more before closing.
    """
    if max_turns < 3:
        raise ValueError("a call needs at least 3 turns")
    if max_turns == 3:
        return (CallState.OPENING, CallState.ASK, CallState.CLOSING)
    if max_turns == 4:
        return (CallState.OPENING, CallState.HOOK, CallState.ASK, CallState.CLOSING)
    extra_asks = (CallState.ASK,) * (max_turns - 5)
    return (*ARC[:4], *extra_asks, CallState.CLOSING)


def check_transition(current: CallState, target: CallState) -> None:
    """Raise `InvalidTransition` if `target` is not reachable from `current`."""
    if target not in TRANSITIONS[current]:
        raise InvalidTransition(f"{current} -> {target}")


@dataclass
class Turn:
    """One exchange, kept for the transcript, the latency eval and the final summary."""

    state: CallState
    user_text: str | None
    caller_text: str
    interrupted: bool = False
    nudge: bool = False
    fallback: bool = False


@dataclass
class SessionSnapshot:
    """Serializable view of a session for logs and the demo UI."""

    call_id: str
    state: CallState
    turn_index: int
    turns: list[Turn] = field(default_factory=list)
    end_reason: str | None = None


def _sanitize(text: str) -> str:
    # The persona prompt forbids markup, but a stray asterisk would be read aloud by TTS.
    return text.replace("*", "").replace("#", "")


class CallSession:
    """Owns the script, the transcript and the state. One instance per call or demo session."""

    def __init__(
        self,
        *,
        call_id: str,
        script: CallScript,
        llm: LLMClient,
        persona_prompt: Prompt | None = None,
        turns_config: dict[str, Any] | None = None,
        safe_word: SafeWordMatcher | None = None,
        on_safe_word: SafeWordCallback | None = None,
    ) -> None:
        self.call_id = call_id
        self.script = script
        self._llm = llm
        self._safe_word = safe_word
        self._on_safe_word = on_safe_word
        self.safe_word_heard = False
        self._background: set[asyncio.Task[None]] = set()
        self._persona = persona_prompt or load_prompt("imbusy.call", "caller.md")
        if turns_config is None:
            _, turns_config = load_yaml_prompt("imbusy.call", "turns.yaml")
        self._config = turns_config
        self._arc = arc_for(script.max_turns)
        self._index = -1
        self._state = CallState.RINGING
        self.turns: list[Turn] = []
        self.end_reason: str | None = None

    @property
    def state(self) -> CallState:
        return self._state

    @property
    def turn_index(self) -> int:
        """Number of caller turns spoken so far (the greeting is turn 1)."""
        return sum(1 for t in self.turns if not t.nudge)

    @property
    def is_final_turn(self) -> bool:
        """True from the moment the CLOSING turn starts; the handler ends the call after it."""
        return self._state is CallState.CLOSING

    @property
    def accepts_input(self) -> bool:
        """False once the farewell has started: later speech is ignored."""
        return self._state not in (CallState.RINGING, CallState.CLOSING, CallState.ENDED)

    def opening_line(self) -> str:
        """The welcome greeting. Moves RINGING -> OPENING and records it as the first caller turn."""
        self._move_to(CallState.OPENING)
        self._index = 0
        self.turns.append(Turn(CallState.OPENING, None, self.script.opening_line))
        return self.script.opening_line

    def system_prompt(self, directive_key: str | None = None) -> str:
        """Persona prompt for the current state: script, rules, transcript note, turn directive."""
        lang = self.script.language.value
        key = directive_key or self._state.value
        directive = self._config["directives"][key][lang]
        alias = (
            self.script.user_alias
            or "their first name only if they have said it; otherwise no name"
        )
        previous = [t.caller_text for t in self.turns if t.caller_text]
        notes = self._config["transcript_notes"]
        if len(previous) <= 1:
            transcript_note = notes["first_turn"]
        else:
            transcript_note = notes["later_turn"].replace(
                "$previous_caller_lines", " / ".join(f'"{line}"' for line in previous)
            )
        return self._persona.render(
            caller_name=self.script.caller_name,
            relationship=self.script.relationship,
            register_note=self._config["registers"][self.script.speech_register.value],
            language_name=self._config["language_names"][lang],
            user_alias=alias,
            situation=self.script.situation,
            ask=self.script.ask,
            urgency=self.script.urgency,
            facts="; ".join(self.script.facts) or "none beyond the situation",
            forbidden="\n".join(
                f"- {rule}" for rule in dict.fromkeys([*BASE_FORBIDDEN, *self.script.forbidden])
            ),
            transcript_note=transcript_note,
            turn_directive=directive,
        )

    def history(self) -> list[ChatMessage]:
        """Transcript as alternating messages, starting with a user turn.

        Interrupted caller turns are already cut to what was heard. Consecutive messages from the
        same side (a nudge, or two prompts in a row) are merged so roles alternate.
        """
        raw: list[ChatMessage] = [ChatMessage(role="user", content=CALL_CONNECTED)]
        for turn in self.turns:
            if turn.user_text:
                raw.append(ChatMessage(role="user", content=turn.user_text))
            if turn.caller_text:
                raw.append(ChatMessage(role="assistant", content=turn.caller_text))
        merged: list[ChatMessage] = []
        for message in raw:
            if merged and merged[-1].role == message.role:
                merged[-1] = ChatMessage(
                    role=message.role, content=f"{merged[-1].content} {message.content}"
                )
            else:
                merged.append(message)
        return merged

    async def respond(self, user_text: str) -> AsyncGenerator[str, None]:
        """Advance to the next state and stream the caller's reply to `user_text`.

        On a model refusal or error, yields a short in-character fallback line from the directives
        file and moves to CLOSING, so the user never hears an error on the phone.

        If the user's turn contains their safe word, the alert fires in the background, the word
        is removed from what the model sees, and this turn is told to start winding the call down
        in the same tone; the next turn is the goodbye.
        """
        wrap_up = self._check_safe_word(user_text)
        if wrap_up:
            assert self._safe_word is not None
            user_text = self._safe_word.redact(user_text)
        if not self.accepts_input:
            return
        target = self._next_state()
        self._move_to(target)
        self._index += 1
        directive: str | None = None
        if wrap_up and target is not CallState.CLOSING:
            directive = "wrap_up"
            # Whatever was left of the arc collapses into the goodbye.
            self._arc = (*self._arc[: self._index + 1], CallState.CLOSING)
        turn = Turn(self._state, user_text, "")
        self.turns.append(turn)
        async for chunk in self._generate(turn, directive_key=directive):
            yield chunk

    def _check_safe_word(self, user_text: str) -> bool:
        """Fire the alert once, the first time the safe word is heard. True if it fired now."""
        if self._safe_word is None or self.safe_word_heard:
            return False
        if not self._safe_word.heard(user_text):
            return False
        self.safe_word_heard = True
        if self._on_safe_word is not None:
            task = asyncio.create_task(self._fire_alert(self._on_safe_word))
            self._background.add(task)
            task.add_done_callback(self._background.discard)
        return True

    async def _fire_alert(self, callback: SafeWordCallback) -> None:
        try:
            await callback()
        except Exception:
            # Never log the phrase or the location; the call id is enough to trace it.
            logger.exception("safe word alert failed", extra={"call_id": self.call_id})

    async def wait_for_alerts(self) -> None:
        """Let a pending alert finish (used when the call ends right after the safe word)."""
        if self._background:
            await asyncio.gather(*self._background, return_exceptions=True)

    async def nudge(self) -> AsyncGenerator[str, None]:
        """Stream a short line after silence ("¿Hola? ¿Me oyes?") without advancing the arc."""
        if not self.accepts_input:
            return
        turn = Turn(self._state, None, "", nudge=True)
        self.turns.append(turn)
        async for chunk in self._generate(turn, directive_key="nudge"):
            yield chunk

    async def _generate(self, turn: Turn, directive_key: str | None) -> AsyncGenerator[str, None]:
        system = self.system_prompt(directive_key)
        messages = self.history()
        if messages[-1].role == "assistant":
            # A nudge after a caller turn: give the model a user turn to answer.
            messages.append(ChatMessage(role="user", content="[silence]"))
        failed = False
        try:
            async for event in self._llm.stream_text(
                role=ModelRole.FAST,
                system=system,
                messages=messages,
                max_tokens=REPLY_MAX_TOKENS,
                effort=Effort.LOW,
            ):
                if isinstance(event, TextDelta):
                    text = _sanitize(event.text)
                    if text:
                        turn.caller_text += text
                        yield text
                elif isinstance(event, StreamEnd) and event.stop_reason is StopReason.REFUSAL:
                    failed = True
        except LLMError:
            logger.exception("caller turn failed", extra={"call_id": self.call_id})
            failed = True
        if failed or not turn.caller_text.strip():
            line = self.fallback_line()
            turn.caller_text = line
            turn.fallback = True
            self._state = CallState.CLOSING
            self._index = len(self._arc) - 1
            yield line

    def fallback_line(self) -> str:
        return str(self._config["fallback_lines"][self.script.language.value])

    def mark_interrupted(self, heard_text: str) -> None:
        """Replace the last caller turn with what the user heard before interrupting."""
        for turn in reversed(self.turns):
            if turn.caller_text:
                turn.caller_text = heard_text.strip()
                turn.interrupted = True
                return

    def end(self, reason: str) -> None:
        """Move to ENDED from any state; idempotent."""
        if self._state is CallState.ENDED:
            return
        self._state = CallState.ENDED
        self.end_reason = reason

    def snapshot(self) -> SessionSnapshot:
        return SessionSnapshot(
            call_id=self.call_id,
            state=self._state,
            turn_index=self.turn_index,
            turns=list(self.turns),
            end_reason=self.end_reason,
        )

    def _next_state(self) -> CallState:
        nxt = self._index + 1
        return self._arc[nxt] if nxt < len(self._arc) else CallState.ENDED

    def _move_to(self, target: CallState) -> None:
        check_transition(self._state, target)
        self._state = target
